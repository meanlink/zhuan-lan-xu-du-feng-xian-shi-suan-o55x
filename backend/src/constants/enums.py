from enum import Enum
class Role(str, Enum):
    admin = 'admin'
    analyst = 'analyst'
    viewer = 'viewer'
class JobStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class SpecStatus(str, Enum):
    active = 'active'
    superseded = 'superseded'
class DatasetLifecycle(str, Enum):
    staging = 'staging'
    current = 'current'
    superseded = 'superseded'
class PlanStatus(str, Enum):
    pending = 'pending'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
